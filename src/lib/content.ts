/** Page content translation helper: falls back to French, then to the key. */
export function pt(lang: Lang, key: string): string {
  return content[lang]?.[key] ?? content.fr[key] ?? key;
}

/** Format a translated string with {0}, {1}, … placeholders. */
export function fmt(template: string, ...values: (string | number)[]): string {
  return template.replace(/\{(\d+)\}/g, (_, i: string) => String(values[Number(i)] ?? ""));
}
