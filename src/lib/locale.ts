/** Map of locale prefixes to country code (extended heuristic) */
const localeMap: Record<string, string> = {
  fr: "FR", be: "BE", lu: "LU",
  es: "ES", it: "IT", pt: "PT", de: "DE",
  sv: "SV", sk: "SK",
  nl: "BE", lb: "LU",
};

/** Detect country from browser locale */
export function detectCountry(): CountryInfo {
  try {
    const raw = Intl.DateTimeFormat().resolvedOptions().locale ?? navigator.language;
    const parts = raw.split("-");
    const key = parts[0]?.toLowerCase() ?? "fr";
    const code = localeMap[key];
    if (code) {
      const found = countries.find((c) => c.code === code);
      if (found) return found;
    }
  } catch {}
  return countries.find((c) => c.code === "ES") ?? countries[3]; // default: Spain
}

export function getCountryByName(name: string): CountryInfo {
  return countries.find((c) => c.name === name) ?? countries.find((c) => c.code === "ES") ?? countries[3];
}

